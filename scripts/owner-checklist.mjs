// Writes docs/research/owner-checklist.md: everything still waiting for the owner, in one place.
//
//   npm run checklist
//
// It collects (1) the unconfirmed items in site.config.mjs, (2) every open `verify:` question in
// the guides (src/content/places, src/content/experiences, src/content/tours) and (3), until
// confirmed.experiences is true, the experience list to review. Answer them in the files
// themselves, then run it again; the checklist is regenerated from scratch each time.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import site from '../site.config.mjs';
import { DESTS } from '../src/data/destinations.mjs';
import { EXPERIENCES } from '../src/data/experiences.mjs';
import { parseFrontMatter } from './lib/frontmatter.mjs';

const ROOT = path.resolve(fileURLToPath(new URL('..', import.meta.url)));
const OUT = path.join(ROOT, 'docs', 'research', 'owner-checklist.md');
const names = Object.fromEntries(DESTS.map((d) => [d.id, d.name]));
// What each site.config.mjs → confirmed flag covers (same wording as the comments there).
const CONFIRM_NOTES = {
  brand: '"Eranorris" is the customer-facing name for the tours business',
  contact: 'the WhatsApp number, phone and email receive tour enquiries',
  address: 'the business location shown in the footer (or set address: null)',
  shuttleService: 'SHUTTLE_TIMING: the driver meets guests in arrivals; at the airport 3 h before a departure',
  vehicles: 'VEHICLES: the models and passenger capacities you operate',
  pickups: 'PICKUPS: you collect from every listed place (incl. Colombo Port, Mattala)',
  hotelOptions: 'the quote form’s hotel choices (Budget / Mid-range / Luxury) are services you offer',
  destinationCopy: 'the 16 destination descriptions, suggested nights and seasons',
  experiences: 'src/data/experiences.mjs: each one is offered/arranged, and its text is right',
  photoRights: 'you are licensed to use every photo in src/images/, and each shows the named place',
};

const lines = [
  '# Owner checklist',
  '',
  'Generated by `npm run checklist` — do not edit by hand. Answer each item where it lives (the',
  'file named in each section), then run the command again.',
  '',
];

// 1. Site-wide facts (site.config.mjs → confirmed)
const unconfirmed = Object.entries(site.confirmed).filter(([, v]) => v !== true);
lines.push(`## Site-wide facts (${unconfirmed.length} open)`, '', 'Set each to `true` in `site.config.mjs → confirmed` once checked.', '');
for (const [k] of unconfirmed) lines.push(`- [ ] \`${k}\`${CONFIRM_NOTES[k] ? ` — ${CONFIRM_NOTES[k]}` : ''}`);
lines.push('');

// 2. Guide questions (verify: lists)
const guides = [];
for (const dir of ['places', 'experiences', 'tours']) {
  const abs = path.join(ROOT, 'src', 'content', dir);
  for (const f of readdirSync(abs).filter((x) => x.endsWith('.md') && !x.startsWith('_')).sort()) {
    const { data } = parseFrontMatter(readFileSync(path.join(abs, f), 'utf8'));
    const verify = [].concat(data.verify || []);
    if (verify.length) guides.push({ file: `src/content/${dir}/${f}`, title: dir === 'places' ? names[f.slice(0, -3)] || f : data.h1 || data.title || f, verify });
  }
}
const open = guides.reduce((n, g) => n + g.verify.length, 0);
lines.push(`## Guide questions (${open} open in ${guides.length} files)`, '', 'Answer them, update the text if needed, and delete each item from the file’s `verify:` list. A page can only be published once its list is empty.', '');
for (const g of guides) {
  lines.push(`### ${g.title} — \`${g.file}\``, '');
  for (const v of g.verify) lines.push(`- [ ] ${v}`);
  lines.push('');
}

// 3. Experiences: one review of the whole list (all are arranged through partners, and the site
// doesn't say who provides them)
const listed = site.confirmed.experiences === true ? [] : EXPERIENCES.filter((e) => e.available !== false);
if (listed.length) {
  lines.push(
    `## Experiences to review (${listed.length} listed)`,
    '',
    'All experiences are arranged through partners, and the site does not show who provides them. Check the list in `src/data/experiences.mjs`: hide any you don’t arrange with `available: false`, correct any text, then set `confirmed.experiences: true` in `site.config.mjs`.',
    '',
  );
  for (const d of DESTS) {
    const xs = listed.filter((e) => e.destinationId === d.id);
    if (xs.length) lines.push(`- **${d.name}** (${xs.length}): ${xs.map((e) => e.name).join(' · ')}`);
  }
  lines.push('');
}

writeFileSync(OUT, lines.join('\n'));
console.log(`Wrote ${path.relative(ROOT, OUT)}: ${unconfirmed.length} site-wide, ${open} guide questions, ${listed.length} experiences to review.`);
