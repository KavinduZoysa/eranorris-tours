// One-off: gets the road distance and the usual drive time between every pair of places
// (PICKUPS and DESTS) and writes them to src/data/route-times.mjs. The site then shows these
// instead of the old straight-line formula. Re-run only when a place is added or moved:
//
//   npm run prepare:routes
//
// Source: Valhalla, an open-source route planner, on the free public server run by FOSSGIS
// (https://valhalla1.openstreetmap.de), with OpenStreetMap road data. Road data © OpenStreetMap
// contributors, ODbL 1.0: the site credits it next to the drive times. The server asks for light
// use only, so this script sends one request at a time, about one a second (around 4 minutes).
//
// Why not Google Maps? Google's terms don't allow saving its directions results, or showing them
// with a map that isn't a Google map (this site's map is drawn from Natural Earth data).
import { writeFile } from 'node:fs/promises';
import { DESTS, PICKUPS } from '../src/data/destinations.mjs';

const API = 'https://valhalla1.openstreetmap.de/route';
const OUT = new URL('../src/data/route-times.mjs', import.meta.url);
const sleep = (ms) => new Promise((r) => setTimeout(r, ms));

// Some map markers are not on a public road. For these, routes go to the place where visitors
// actually arrive by car. The marker on the map does not move.
const ROAD_POINT = {
  yala: { lat: 6.2764, lng: 81.403, why: 'the main park entrance at Palatupana (the marker is inside the park)' },
  udawalawe: { lat: 6.4403, lng: 80.8905, why: 'the park entrance and ticket office (the marker is inside the park)' },
  'adams-peak': { lat: 6.8204, lng: 80.5176, why: 'Dalhousie, where the main path starts (the marker is the summit)' },
};

const places = [...PICKUPS, ...DESTS].map((p) => {
  const pt = ROAD_POINT[p.id] || p;
  return { id: p.id, lat: pt.lat, lng: pt.lng };
});

async function route(a, b) {
  const q = {
    locations: [
      { lat: a.lat, lon: a.lng },
      { lat: b.lat, lon: b.lng },
    ],
    costing: 'auto',
    units: 'kilometers',
    directions_type: 'none',
  };
  const url = `${API}?json=${encodeURIComponent(JSON.stringify(q))}`;
  for (let tries = 1; tries <= 4; tries++) {
    try {
      const r = await fetch(url, { headers: { 'User-Agent': 'route-times-script/1.0' } });
      if (r.ok) {
        const s = (await r.json()).trip.summary;
        return [Math.round(s.length), Math.round(s.time / 60)];
      }
      console.warn(`  ${a.id} → ${b.id}: HTTP ${r.status}, trying again`);
    } catch (e) {
      console.warn(`  ${a.id} → ${b.id}: ${e.message}, trying again`);
    }
    await sleep(3000 * tries);
  }
  throw new Error(`No route found from ${a.id} to ${b.id}`);
}

// Each pair is asked once, in one direction; the times are close either way. Places with the
// same position (e.g. the Kandy pickup and the Kandy destination) are not asked about.
const legs = [];
const memo = new Map();
const total = (places.length * (places.length - 1)) / 2;
let n = 0;
for (let i = 0; i < places.length; i++) {
  for (let j = i + 1; j < places.length; j++) {
    const a = places[i],
      b = places[j];
    n++;
    if (a.lat === b.lat && a.lng === b.lng) continue;
    const key = [a, b].map((p) => `${p.lat},${p.lng}`).join('|');
    if (!memo.has(key)) {
      memo.set(key, await route(a, b));
      await sleep(1100);
    }
    const [km, min] = memo.get(key);
    legs.push(`  '${a.id}|${b.id}': [${km}, ${min}],`);
    if (n % 25 === 0) console.log(`${n} of ${total} pairs`);
  }
}

const today = new Date().toISOString().slice(0, 10);
const roadNotes = Object.entries(ROAD_POINT).map(([id, p]) => `//   ${id}: ${p.why}`);
await writeFile(
  OUT,
  `// Generated by scripts/route-times.mjs on ${today}. Do not edit by hand: run \`npm run prepare:routes\`.
//
// Road distance in km and usual drive time in minutes for each pair of places, in either
// direction, e.g. 'cmb|galle': [161, 145] means 161 km and about 145 minutes. Source: Valhalla
// (car) on OpenStreetMap road data. Road data © OpenStreetMap contributors, ODbL 1.0
// (https://www.openstreetmap.org/copyright). The times are for normal driving, without stops
// or heavy traffic. Your own figures in ROUTE_TIMES (src/data/destinations.mjs) win over these.
//
// These places are routed to a road point instead of their map marker:
${roadNotes.join('\n')}
export const ROAD_LEGS = {
${legs.join('\n')}
};
`,
);
console.log(`Wrote ${legs.length} pairs (${memo.size} routes asked) to src/data/route-times.mjs`);
